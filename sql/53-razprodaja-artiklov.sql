-- Pred vsakim vpisom/posodobitvijo artikla: razprodajni artikel brez zaloge ne sme biti objavljen.
create or replace function razprodaja_skrij_artikel() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.objavljeno and coalesce(new.zaloga, 0) <= 0
     and exists (select 1 from artikli_razprodaja r where r.sifra = new.sifra) then
    new.objavljeno := false;
  end if;
  return new;
end $$;

drop trigger if exists artikli_razprodaja_skrij on artikli;
create trigger artikli_razprodaja_skrij
  before insert or update of zaloga, objavljeno on artikli
  for each row execute function razprodaja_skrij_artikel();

-- Ko se razprodajni artikel skrije: če izdelek nima več nobenega vidnega artikla, skrij še izdelek.
create or replace function razprodaja_skrij_izdelek() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.izdelek_id is not null and not new.objavljeno
     and exists (select 1 from artikli_razprodaja r where r.sifra = new.sifra)
     and not exists (select 1 from artikli a where a.izdelek_id = new.izdelek_id and a.objavljeno) then
    update izdelki set objavljeno = false where id = new.izdelek_id and objavljeno;
  end if;
  return null;
end $$;

drop trigger if exists artikli_razprodaja_izdelek on artikli;
create trigger artikli_razprodaja_izdelek
  after insert or update of zaloga, objavljeno on artikli
  for each row execute function razprodaja_skrij_izdelek();

-- Novi artikli iz Vasca, ki so v razprodaji, se ne predlagajo za dodajanje.
create or replace function razprodaja_novi_ignoriraj() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'nov' and exists (select 1 from artikli_razprodaja r where r.sifra = new.sifra) then
    new.status := 'ignoriraj';
  end if;
  return new;
end $$;

drop trigger if exists vasco_novi_razprodaja on vasco_novi_artikli;
create trigger vasco_novi_razprodaja
  before insert or update on vasco_novi_artikli
  for each row execute function razprodaja_novi_ignoriraj();

update vasco_novi_artikli set status = 'ignoriraj'
where status = 'nov' and sifra in (select sifra from artikli_razprodaja);

-- Pregled za admin (Sinhronizacija): razprodajni artikli, ki so na spletu.
create or replace view artikli_razprodaja_stanje as
  select a.id, a.sifra, a.naziv, a.dimenzija, a.zaloga, a.objavljeno, a.izdelek_id, r.din
  from artikli a join artikli_razprodaja r on r.sifra = a.sifra;
revoke all on artikli_razprodaja_stanje from anon, authenticated;

-- Enkratno: sproži pravilo na obstoječih artiklih (brez zaloge se skrijejo zdaj).
update artikli set objavljeno = objavljeno
where sifra in (select sifra from artikli_razprodaja);

-- Rezultat
select
  count(*) filter (where objavljeno)                    as se_vidni_z_zalogo,
  count(*) filter (where not objavljeno)                as skriti,
  count(*)                                              as na_spletu_skupaj
from artikli_razprodaja_stanje;
