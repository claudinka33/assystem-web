-- Kode za popust (assystem-web). Varno za ponovni zagon.
create table if not exists popust_kode (
  id bigint generated by default as identity primary key,
  koda text not null unique,                       -- vedno velike črke, npr. JESEN10
  opis text,                                       -- interni opis
  tip text not null default 'odstotek'
    check (tip in ('odstotek', 'znesek', 'dostava')),   -- % popusta, fiksen znesek (€ z DDV) ali brezplačna dostava
  vrednost numeric not null default 0,
  velja_za text not null default 'trgovina'
    check (velja_za in ('trgovina', 'kategorija', 'znamka', 'artikel')),
  kategorija_id text,                              -- velja_za = kategorija (vključno s podkategorijami)
  znamka text,                                     -- velja_za = znamka: ASfix, ASco, MUNGO
  artikel_sifra text,                              -- velja_za = artikel
  kupci text not null default 'vsi' check (kupci in ('vsi', 'b2c', 'b2b')),
  min_znesek numeric,                              -- najmanjša vrednost blaga z DDV
  max_uporab int,                                  -- skupaj; prazno = neomejeno
  uporabljeno int not null default 0,
  velja_od date,
  velja_do date,
  aktivno boolean not null default true,
  ustvarjeno timestamptz not null default now()
);
alter table popust_kode enable row level security;

alter table narocila add column if not exists popust_koda text;
alter table narocilo_postavke add column if not exists popust_neto numeric not null default 0;
